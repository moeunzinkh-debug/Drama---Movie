import type { NextConfig } from "next";

/**
 * Security headers.
 *
 * Kept in one place so the policy is reviewable. Notes:
 *
 * - CSP: `script-src 'self' 'unsafe-inline'` is required because Next.js emits
 *   inline bootstrap scripts and nonces are not available for statically
 *   optimised pages. There is no third-party script today. Before AdSense is
 *   enabled you MUST add its domains here (see docs/ADS_INTEGRATION.md) — the
 *   policy below intentionally blocks ad networks until that review happens.
 * - `frame-ancestors 'none'` blocks clickjacking of the player.
 * - HSTS is only sent over HTTPS, so local http development is unaffected.
 * - Permissions-Policy disables sensors and features the site never uses.
 */
const isDev = process.env.NODE_ENV !== "production";

// `headers()` is evaluated at build time, so this can only ever see what the
// build environment had. The policy therefore also allows the Supabase wildcard
// below: the Worker may be configured with a project that did not exist yet when
// the bundle was built, and a CSP that omits it blocks every auth request.
const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL ?? "";
const supabaseHost = (() => {
  try {
    return supabaseUrl ? new URL(supabaseUrl).host : "";
  } catch {
    return "";
  }
})();

const csp = [
  "default-src 'self'",
  // Next.js inlines its bootstrap; dev also needs eval for the HMR runtime.
  `script-src 'self' 'unsafe-inline'${isDev ? " 'unsafe-eval'" : ""}`,
  "style-src 'self' 'unsafe-inline'",
  // Posters are same-origin SVG; Supabase avatars and video posters are external.
  `img-src 'self' data: blob: https://*.supabase.co${
    supabaseHost ? ` https://${supabaseHost}` : ""
  }`,
  // HLS segments come from Cloudflare Stream; Supabase is needed for auth/session.
  `media-src 'self' blob: https://*.cloudflarestream.com https://*.cloudflare.com https://*.supabase.co${
    supabaseHost ? ` https://${supabaseHost}` : ""
  }`,
  "font-src 'self' data:",
  // supabase-js talks to Postgres over HTTPS; dev uses an HMR websocket.
  `connect-src 'self'${isDev ? " ws: wss:" : ""} https://*.supabase.co wss://*.supabase.co${
    supabaseHost ? ` https://${supabaseHost} wss://${supabaseHost}` : ""
  } https://*.cloudflarestream.com`,
  "frame-src 'self' https://*.cloudflarestream.com",
  "worker-src 'self' blob:",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
  ...(isDev ? [] : ["upgrade-insecure-requests"]),
].join("; ");

const securityHeaders = [
  { key: "Content-Security-Policy", value: csp },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  {
    key: "Permissions-Policy",
    value: [
      "camera=()",
      "microphone=()",
      "geolocation=()",
      "payment=()",
      "usb=()",
      "magnetometer=()",
      "gyroscope=()",
      "accelerometer=()",
    ].join(", "),
  },
  // Only meaningful over HTTPS; browsers ignore it on http://localhost.
  { key: "Strict-Transport-Security", value: "max-age=31536000; includeSubDomains" },
  { key: "X-DNS-Prefetch-Control", value: "off" },
];

const nextConfig: NextConfig = {
  poweredByHeader: false,
  reactStrictMode: true,
  images: {
    // Poster/backdrop art is generated by our own route handlers.
    unoptimized: true,
  },
  async headers() {
    return [
      { source: "/:path*", headers: securityHeaders },
      {
        // Never let a proxy or browser cache authenticated HTML.
        source: "/(admin|my-list|request|watch|login|auth)/:path*",
        headers: [{ key: "Cache-Control", value: "private, no-store, max-age=0" }],
      },
      {
        // Generated icons are immutable.
        source: "/:file(icon|icon-maskable|favicon)-:size(\\d+).png",
        headers: [{ key: "Cache-Control", value: "public, max-age=31536000, immutable" }],
      },
    ];
  },
};

export default nextConfig;
